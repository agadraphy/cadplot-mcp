"""Local CLI for the same reviewed, copy-only translation service as the MCP.

No network, embedded language model, implicit approval, or remote fallback.
"""

from __future__ import annotations

import argparse
import json
import os
from pathlib import Path
from typing import Literal

from pydantic import Field, model_validator

from cadplot_mcp.cli_auth import CLIError
from cadplot_mcp.config import load_config
from cadplot_mcp.security import require_plain_directory_path
from cadplot_mcp.tool_types import InventoryIdString, PathString, PlanIdString
from cadplot_mcp.translation import (
    ClosedModel,
    Decisions,
    ReviewedText,
    TranslationDecision,
    TranslationPlan,
    inventory_page,
    review_record,
)
from cadplot_mcp.translation_service import (
    apply_translation,
    prepare_plan,
    scan_source,
)

MAX_REVIEW_BYTES = 32 * 1024 * 1024


class ReviewFile(ClosedModel):
    schema_version: Literal[1] = 1
    drawing: PathString
    inventory_id: InventoryIdString
    instructions: str = Field(max_length=4000)
    records: list[ReviewedText] = Field(max_length=10_000)
    blockers: list[str] = Field(max_length=100_000)
    decisions: Decisions


class PlanFile(ClosedModel):
    schema_version: Literal[1] = 1
    review: ReviewFile
    plan: TranslationPlan

    @model_validator(mode="after")
    def same_inventory(self):
        if (
            self.review.drawing != self.plan.drawing
            or self.review.inventory_id != self.plan.inventory_id
        ):
            raise ValueError("Plan and review must refer to the same drawing inventory.")
        return self


def register_commands(commands) -> None:
    translate = commands.add_parser(
        "translate", help="LOCAL AutoCAD text translation: scan, review, plan, approved copy"
    )
    actions = translate.add_subparsers(dest="translation_action", required=True)
    for action in ("scan", "plan", "check", "apply"):
        command = actions.add_parser(action)
        command.add_argument("--config", default=os.getenv("CADPLOT_CONFIG"))
        if action == "scan":
            command.add_argument("drawing", help="saved, CLOSED local DWG under allowed_roots")
        elif action == "plan":
            command.add_argument("--review", required=True, help="completed review JSON")
        else:
            command.add_argument(
                "--plan", required=True, help="exact previously generated plan JSON"
            )
        if action in ("scan", "plan"):
            command.add_argument(
                "--output", required=True, help="NEW private .json file; never overwrite"
            )
        if action == "apply":
            command.add_argument(
                "--approve",
                required=True,
                type=approval_id,
                help="explicitly approved sha256: plan ID; never infer approval from a file",
            )


def approval_id(value: str) -> str:
    from pydantic import TypeAdapter, ValidationError

    try:
        return TypeAdapter(PlanIdString).validate_python(value)
    except ValidationError:
        raise argparse.ArgumentTypeError(
            "Copy the exact sha256: plan ID after reviewing changes."
        ) from None


def _unique_object(pairs):
    result = {}
    for key, value in pairs:
        if key in result:
            raise ValueError("Duplicate JSON keys are not accepted.")
        result[key] = value
    return result


def read_file(path: str, model):
    try:
        candidate = Path(path)
        if candidate.suffix.lower() != ".json" or not candidate.is_file():
            raise ValueError("Expected JSON file.")
        with candidate.open("rb") as stream:
            raw = stream.read(MAX_REVIEW_BYTES + 1)
        if len(raw) > MAX_REVIEW_BYTES:
            raise ValueError("Review exceeds the size bound.")
        # Accept the BOM generated by Windows editors, but not duplicate keys or coercion.
        return model.model_validate(
            json.loads(raw.decode("utf-8-sig"), object_pairs_hook=_unique_object)
        )
    except (OSError, ValueError, TypeError, RecursionError):
        raise CLIError(
            "invalid_translation_file",
            "Expected a bounded UTF-8 translation JSON with the exact schema and unique keys.",
            2,
        ) from None


def output_path(path: str) -> Path:
    candidate = Path(path).expanduser().absolute()
    try:
        parent = require_plain_directory_path(candidate.parent)
        if not parent.is_dir() or candidate.suffix.lower() != ".json":
            raise ValueError("Expected an existing plain directory and .json filename.")
        # lexists also catches dangling symlinks. Final exclusive open repeats this check.
        if os.path.lexists(candidate):
            raise FileExistsError
    except (OSError, ValueError):
        raise CLIError(
            "invalid_translation_output",
            "Choose a NEW .json filename in an existing private directory without links/junctions.",
            2,
        ) from None
    return candidate


def write_file(path: Path, value: ClosedModel) -> None:
    raw = value.model_dump_json(indent=2).encode("utf-8")
    if len(raw) > MAX_REVIEW_BYTES:
        raise CLIError(
            "translation_too_large", "Review/plan exceeds 32 MiB; nothing was truncated.", 2
        )
    try:
        output_path(str(path))
        with path.open("xb") as stream:
            stream.write(raw)
            stream.flush()
            os.fsync(stream.fileno())
    except OSError:
        raise CLIError(
            "translation_output_failed",
            "Could not create the new JSON file. Any partial file is not a valid review/plan.",
            2,
        ) from None


def execute_translation(args: argparse.Namespace) -> dict:
    """Run synchronously: the COM subprocess owns the bounded timeout and recovery semantics."""
    if os.environ.get("CADPLOT_ENABLE_TRANSLATION") != "1":
        raise CLIError(
            "translation_disabled",
            "Authorize local translation with CADPLOT_ENABLE_TRANSLATION=1. No remote fallback.",
            2,
        )
    if not args.config:
        raise CLIError("translation_config_required", "Pass --config or set CADPLOT_CONFIG.", 2)
    try:
        config = load_config(args.config)
    except (OSError, ValueError):
        raise CLIError(
            "invalid_translation_config", "Check the approved local CadPlot configuration.", 2
        ) from None

    action = args.translation_action
    destination = output_path(args.output) if action in ("scan", "plan") else None
    try:
        if action == "scan":
            source, fingerprint, snapshot = scan_source(args.drawing, config)
            page = inventory_page(
                source, fingerprint, snapshot, expected_id=None, offset=0, limit=100
            )
            # A single consistent COM scan, not repeated rescans for each page.
            records = []
            for record in snapshot.records:
                try:
                    records.append(review_record(record))
                except ValueError:
                    records.append(ReviewedText(**record.model_dump(), spans=[]))
            review = ReviewFile(
                drawing=source,
                inventory_id=page.inventory_id,
                instructions=page.instructions,
                records=records,
                blockers=page.blockers,
                decisions=[
                    TranslationDecision(
                        span_id=span.id,
                        source=span.text,
                        source_language="uncertain",
                        target=span.text,
                    )
                    for record in records
                    for span in record.spans
                ],
            )
            write_file(destination, review)
            return {
                "status": "review_required",
                "mode": "local",
                "review_file": str(destination),
                "inventory_id": review.inventory_id,
                "total_records": len(records),
                "total_review_spans": len(review.decisions),
                "blockers": review.blockers,
                "instructions": review.instructions,
            }
        if action == "plan":
            review = read_file(args.review, ReviewFile)
            plan = prepare_plan(review.drawing, config, review.inventory_id, review.decisions)
            write_file(destination, PlanFile(review=review, plan=plan))
            return {"mode": "local", "plan_file": str(destination), **plan.model_dump()}

        bundle = read_file(args.plan, PlanFile)
        if action == "apply" and args.approve != bundle.plan.plan_id:
            raise CLIError(
                "translation_approval_mismatch", "Approval does not match the saved plan.", 2
            )
        current = prepare_plan(
            bundle.review.drawing, config, bundle.review.inventory_id, bundle.review.decisions
        )
        if current != bundle.plan:
            raise CLIError(
                "translation_plan_changed",
                "Drawing, decisions or saved plan changed; create and review a new plan.",
                2,
            )
        if action == "check":
            return {"mode": "local", "current": True, **current.model_dump()}
        receipt = apply_translation(
            bundle.review.drawing,
            config,
            bundle.review.inventory_id,
            bundle.review.decisions,
            args.approve,
        )
        return {"mode": "local", **receipt.model_dump()}
    except CLIError:
        raise
    except (OSError, ValueError, RuntimeError):
        # Validation/COM messages can include company drawing text or paths.
        raise CLIError(
            "translation_failed",
            "Translation did not complete. Check the saved/closed DWG, allowed roots, AutoCAD, "
            "review completeness and current inventory. No success receipt was returned; "
            "inspect retained recovery files before retrying.",
            2,
        ) from None
